"""
GitPublishAgent - Pushes branch, creates PR, computes official score, and writes results.json.
"""

import os
import re
import json
import logging
import subprocess
from pathlib import Path
from typing import Dict, Any, List, Optional

from rift.state import AgentState
from rift.utils import check_gh_available, check_gh_authenticated, create_pr_with_gh

logger = logging.getLogger("rift.agents.publisher")

ROOT_DIR = Path(__file__).resolve().parent.parent.parent


def _run_cmd(cmd: List[str], cwd: Path) -> subprocess.CompletedProcess:
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env)


def calculate_score(total_time_seconds: float, total_commits: int, ci_cd_passed: bool) -> Dict[str, Any]:
    """Calculate score strictly according to RIFT 2026 specifications.
    • Base score: 100 points
    • Speed bonus applied (+10 if < 5 minutes)
    • Efficiency penalty (-2 per commit over 20)
    • Final total score displayed prominently
    """
    base_score = 100
    speed_bonus = 10 if (total_time_seconds < 300 and ci_cd_passed) else 0
    over_commits = max(0, total_commits - 20)
    efficiency_penalty = over_commits * 2

    final_score = max(0, base_score + speed_bonus - efficiency_penalty) if ci_cd_passed else 0

    return {
        "base_score": base_score,
        "speed_bonus": speed_bonus,
        "efficiency_penalty": efficiency_penalty,
        "final_score": final_score
    }


def git_publish_agent(state: AgentState) -> Dict[str, Any]:
    """Agent node that pushes changes, creates PR, writes results.json, and outputs score."""
    logger.info("--- [GitPublishAgent] Finalizing run, publishing branch, and generating results.json ---")

    clone_path = Path(state["clone_path"])
    branch_name = state["branch_name"]
    token = state.get("token") or os.environ.get("GITHUB_TOKEN", "")
    repo_url = state["repo_url"]
    ci_cd_passed = state.get("ci_cd_passed", False)
    fixes_applied = state.get("fixes_applied", [])
    history = state.get("iteration_history", [])

    # Count actual git commits on this branch
    commit_count_res = _run_cmd(["git", "rev-list", "--count", "HEAD"], cwd=clone_path)
    total_commits = int(commit_count_res.stdout.strip()) if commit_count_res.returncode == 0 and commit_count_res.stdout.strip().isdigit() else len(history)

    total_time = state.get("total_time_seconds", 60.0)
    score_breakdown = calculate_score(total_time, total_commits, ci_cd_passed)

    # 1. Push branch to origin
    push_success = False
    logger.info(f"Pushing branch {branch_name}...")

    # Fast network timeouts
    _run_cmd(["git", "config", "http.lowSpeedLimit", "1"], cwd=clone_path)
    _run_cmd(["git", "config", "http.lowSpeedTime", "30"], cwd=clone_path)

    push_res = _run_cmd(["git", "push", "origin", branch_name, "-u", "--force"], cwd=clone_path)
    if push_res.returncode == 0:
        push_success = True
        logger.info(f"Successfully pushed branch: {branch_name}")
    else:
        logger.warning(f"Git push failed: {push_res.stderr or push_res.stdout}")

    # 2. Pull Request Creation
    pr_number = None
    pr_title = f"[AI Fix] {branch_name}"
    summary_lines = "\n".join(
        f"- {f.get('bug_type')}: {f.get('fix')} (line {f.get('line_number')})"
        for f in fixes_applied
    )
    pr_body = (
        f"## RIFT 2026 Autonomous Healing Summary\n"
        f"**CI/CD Status:** {'PASSED' if ci_cd_passed else 'FAILED'}\n"
        f"**Iterations:** {state.get('current_iteration', 1)}/{state.get('max_iterations', 5)}\n"
        f"**Fixes Applied:** {len(fixes_applied)}\n\n"
        f"### Applied Fixes\n{summary_lines}\n\n---\n"
        f"*Generated by Autonomous CI/CD Healing Agent*"
    )

    # Try PyGithub
    if token:
        try:
            from github import Github
            g = Github(token, timeout=25)
            m = re.search(r'github\.com[/:]([^/]+)/([^/.]+)', repo_url)
            if m:
                owner, rname = m.groups()
                repo = g.get_repo(f"{owner}/{rname.replace('.git', '')}")
                head_ref = f"{g.get_user().login}:{branch_name}" if state.get("forked_repo_url") else branch_name
                pr = repo.create_pull(title=pr_title, body=pr_body, head=head_ref, base="main")
                pr_number = pr.number
                logger.info(f"Created Pull Request #{pr_number}")
        except Exception as e:
            logger.warning(f"PyGithub PR creation failed: {e}")

    # Fallback to gh CLI
    if not pr_number and check_gh_available() and check_gh_authenticated():
        pr_number = create_pr_with_gh(repo_url, branch_name, pr_title, pr_body, base_branch="main")

    # 3. Assemble and save results.json
    results_payload = {
        "repository_url": repo_url,
        "team_name": state["team_name"],
        "leader_name": state["leader_name"],
        "branch_name": branch_name,
        "final_status": "PASSED" if ci_cd_passed else "FAILED",
        "total_time_seconds": round(total_time, 2),
        "total_failures_detected": len(state.get("detected_errors", [])),
        "total_fixes_applied": len([f for f in fixes_applied if f.get("status") == "Fixed"]),
        "iterations_used": state.get("current_iteration", 1),
        "max_iterations": state.get("max_iterations", 5),
        "score_breakdown": score_breakdown,
        "pull_request_number": pr_number,
        "ci_cd_timeline": history,
        "fixes": fixes_applied
    }

    results_file = ROOT_DIR / "results.json"
    try:
        with open(results_file, "w", encoding="utf-8") as f:
            json.dump(results_payload, f, indent=2)
        logger.info(f"Generated results.json at {results_file}")
    except Exception as e:
        logger.error(f"Failed to write results.json: {e}")

    return {
        "ci_cd_passed": ci_cd_passed,
        "score": score_breakdown,
        "pr_number": pr_number,
        "results_json_path": str(results_file),
        "final_results": results_payload
    }
